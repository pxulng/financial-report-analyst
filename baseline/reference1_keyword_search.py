"""Reference 1: keyword search in the report, no AI (the floor of the study).
For each item, a fixed list of label patterns (the same for every company, written once, not tuned per company).
The first line that matches a pattern and carries a number is read; the first number on that line (or the next) is the value.
It cannot decide that an item is not applicable or absent from the report: it returns what a plain search finds, or null.
Usage: python3 reference1_keyword_search.py <report.md> <TICKER> > sheet.json"""
import re,sys,json
PAT={
 'revenue':[r'^\W*total net sales',r'^\W*total revenues?\b',r'^\W*total net revenues?',r'^\W*revenues?\b',r'^\W*sales to customers',r'^\W*net sales\b'],
 'operating_income':[r'^\W*operating income',r'^\W*income from operations',r'^\W*earnings from operations'],
 'net_income':[r'^\W*net income attributable to',r'^\W*net earnings attributable to',r'^\W*net income\b',r'^\W*net earnings\b'],
 'diluted_eps':[r'^\W*diluted\b',r'earnings per share.{0,12}diluted',r'diluted.{0,30}per (common )?share'],
 'operating_cash_flow':[r'^\W*(net )?cash (generated by|provided by|from).{0,25}operat'],
 'capex':[r'payments for acquisition of property',r'purchases? of property',r'additions to property',r'payments for property and equipment',r'capital expenditures'],
 'cash':[r'^\W*cash and cash equivalents\b',r'^\W*cash and equivalents\b'],
 'total_financial_debt':[r'^\W*long-term debt\b',r'^\W*term debt\b'],
 'shareholders_equity':[r"^\W*total (shareholders|stockholders)[’' ]*s?[’']? equity",r'^\W*total equity'],
}
NUM=re.compile(r'\(?\$?\s?(\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+\.\d+|\d+)\)?')
def first_number(s):
    m=NUM.search(s); 
    if not m: return None
    v=float(m.group(1).replace(',',''))
    return -v if m.group(0).strip().startswith('(') and not m.group(0).strip().startswith('($') and False else v
f,tk=sys.argv[1],sys.argv[2]
L=open(f,encoding='utf-8',errors='ignore').read().replace('\t',' ').split('\n')
figs=[]
for item,pats in PAT.items():
    val=None;src=''
    for p in pats:
        for i,l in enumerate(L):
            if re.search(p,l,re.I):
                tail=re.sub(p,'',l,count=1,flags=re.I)
                v=first_number(tail) if re.search(r'\d',tail) else first_number(L[i+1] if i+1<len(L) else '')
                if v is not None and not (1990<=v<=2040 and float(v).is_integer()):
                    val=v;src=f"line {i+1}"; break
        if val is not None: break
    figs.append({'item':item,'value':val,'status':'found' if val is not None else 'not_in_report','source':src,'note':''})
print(json.dumps({'figures':figs,'computed':[],'segments':{},'major_risks':[],'not_in_report':[],'limits':['keyword search, no reasoning']}))
