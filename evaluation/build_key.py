BASE="../data/10k/"
out={}; problems=[]
for t,c in D.items():
    txt=open(BASE+c["file"],encoding="utf-8",errors="ignore").read().replace("\t"," ")
    L=txt.split("\n")
    def locate(lbl,val,start=0):
        for i,l in enumerate(L):
            if re.search(lbl,l,re.I):
                w=" ".join(L[max(0,i-1):i+3])
                if val in w: return i+1
        return None
    rec={"file":c["file"],"fiscal_year":c["fy"],"sha256":hashlib.sha256(open(BASE+c["file"],"rb").read()).hexdigest(),"unit":"USD millions (EPS in USD per share)","items":{}}
    for k in ["revenue","operating_income","net_income","diluted_eps","operating_cash_flow","capex","cash","equity"]:
        v=c[k]
        if v==NA: rec["items"][k]={"status":NA}; continue
        if v==EXC: rec["items"][k]={"status":EXC}; continue
        ln=locate(v[0],v[1])
        if ln is None: problems.append((t,k)); 
        rec["items"][k]={"status":"found","value":v[2],"printed":v[1],"label":v[0].replace("\\",""),"line":ln}
    ln=locate(c["prev_revenue"][0],c["prev_revenue"][1])
    if ln is None: problems.append((t,"prev_revenue"))
    rec["items"]["prev_revenue"]={"status":"found","value":c["prev_revenue"][2],"printed":c["prev_revenue"][1],"line":ln}
    parts=[]
    for lbl,pv,nv in c["debt"]:
        ln=locate(lbl,pv)
        if ln is None: problems.append((t,"debt:"+lbl+pv))
        parts.append({"label":lbl.replace("\\",""),"printed":pv,"value":nv,"line":ln})
    rec["items"]["debt"]={"status":"found","value":round(sum(p["value"] for p in parts),1),"parts":parts}
    I=rec["items"]
    # computed items, frozen formulas
    cm={}
    cm["revenue_growth"]={"status":"found","value":round(I["revenue"]["value"]/I["prev_revenue"]["value"]-1,4)}
    if I["operating_income"]["status"]==NA: cm["operating_margin"]={"status":NA}
    else: cm["operating_margin"]={"status":"found","value":round(I["operating_income"]["value"]/I["revenue"]["value"],4)}
    if I["capex"]["status"]==EXC: cm["free_cash_flow"]={"status":EXC}
    elif I["capex"]["status"]==NA: cm["free_cash_flow"]={"status":NA}
    else: cm["free_cash_flow"]={"status":"found","value":round(I["operating_cash_flow"]["value"]-I["capex"]["value"],1)}
    if I["cash"]["status"]==NA: cm["net_debt"]={"status":NA}
    else: cm["net_debt"]={"status":"found","value":round(I["debt"]["value"]-I["cash"]["value"],1)}
    rec["computed"]=cm; rec["segments"]=c["segments"]
    out[t]=rec
json.dump(out,open("key.json","w"),indent=1,ensure_ascii=False)
print("problems:",problems)
